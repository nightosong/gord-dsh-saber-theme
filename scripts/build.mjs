import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

export const root = fileURLToPath(new URL('../', import.meta.url));
export async function readVersion() {
  return (await readFile(path.join(root, 'VERSION'), 'utf8')).trim();
}
export async function build() {
  const read = file => readFile(path.join(root, file), 'utf8');
  const pkg = JSON.parse(await read('package.json'));
  const version = await readVersion();
  if (pkg.version !== version || !/^\d+\.\d+\.\d+$/.test(version)) throw new Error('VERSION and package.json must contain the same release version');
  const tokens = JSON.parse(await read('theme/tokens.json'));
  for (const [key, value] of Object.entries(tokens)) {
    if (!key.startsWith('--dsw-') || typeof value.light !== 'string' || typeof value.dark !== 'string') throw new Error(`Invalid token: ${key}`);
  }
  let css = await read('theme/saber.css');
  const pictures = [];
  for (const [variable, file, mime] of [
    ['standing', 'saber-standing.webp', 'image/webp'], ['home', 'saber-home.jpg', 'image/jpeg']
  ]) {
    const bytes = await readFile(path.join(root, 'theme/assets', file));
    const url = `url("data:${mime};base64,${bytes.toString('base64')}")`;
    // Keep each data URL below Chromium's 1 MiB custom-property limit.
    if (url.length >= 1024 * 1024) throw new Error(`Optimize ${file}: its CSS data URL exceeds 1 MiB`);
    pictures.push(`--saber-${variable}:${url}`);
  }
  css = `body[data-dsh-saber]{${pictures.join(';')}}\n${css}`;
  const source = await read('src/client.js');
  const client = `// Generated by scripts/build.mjs — version ${version}\nwindow.__ModuleLoader__.load({\n  id: ${JSON.stringify(pkg.name)},\n  factory: () => {\nconst SABER_CSS = ${JSON.stringify(css)};\nconst SABER_TOKENS = ${JSON.stringify(tokens)};\nconst SABER_VERSION = ${JSON.stringify(version)};\n${source}\nreturn { inject: ['theme'], apply };\n  }\n});\n`;
  await mkdir(path.join(root, 'lib'), { recursive: true });
  await writeFile(path.join(root, 'lib/client.js'), client);
  await writeFile(path.join(root, 'lib/index.js'), await read('src/index.js'));
  return { version, bytes: Buffer.byteLength(client) };
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { console.log(await build()); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
