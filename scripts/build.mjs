import { mkdir, readFile, writeFile, readdir, rm } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

export const root = fileURLToPath(new URL('../', import.meta.url));
export async function readVersion() {
  return (await readFile(path.join(root, 'VERSION'), 'utf8')).trim();
}
export async function build() {
  const read = file => readFile(path.join(root, file), 'utf8');
  const pkg = JSON.parse(await read('package.json'));
  const version = await readVersion();
  if (pkg.version !== version || !/^\d+\.\d+\.\d+$/.test(version)) throw new Error('VERSION and package.json must contain the same release version');
  const tokens = JSON.parse(await read('theme/tokens.json'));
  for (const [key, value] of Object.entries(tokens)) {
    if (!key.startsWith('--dsw-') || typeof value.light !== 'string' || typeof value.dark !== 'string') throw new Error(`Invalid token: ${key}`);
  }
  let css = await read('theme/saber.css');
  const pictures = [];
  for (const [variable, file, mime] of [
    ['standing', 'saber-standing.webp', 'image/webp'], ['home', 'saber-home.jpg', 'image/jpeg']
  ]) {
    const bytes = await readFile(path.join(root, 'theme/assets', file));
    const url = `url("data:${mime};base64,${bytes.toString('base64')}")`;
    // Keep each data URL below Chromium's 1 MiB custom-property limit.
    if (url.length >= 1024 * 1024) throw new Error(`Optimize ${file}: its CSS data URL exceeds 1 MiB`);
    pictures.push(`--saber-${variable}:${url}`);
  }
  css = `body[data-dsh-saber]{${pictures.join(';')}}\n${css}`;
  const source = await read('src/client.js');
  const rotation = JSON.parse(await read('theme/rotation.json'));
  if (!Number.isFinite(rotation.intervalMinutes) || rotation.intervalMinutes < 1 || rotation.intervalMinutes > 1440) throw new Error('Rotation interval must be between 1 and 1440 minutes');
  const assets = ['saber-standing.webp', ...(await readdir(path.join(root, 'theme/assets/rotation'))).filter(file => /^bg\d{2}-[\w-]+\.webp$/.test(file)).sort().map(file => `rotation/${file}`)];
  const files = assets.map((_, i) => `client.wallpaper-${i}.js`);
  const runtime = await read('src/rotation.js');
  const client = `// Generated by scripts/build.mjs — version ${version}\nwindow.__ModuleLoader__.load({\n  id: ${JSON.stringify(pkg.name)},\n  factory: (require) => {\nconst SABER_CSS = ${JSON.stringify(css)};\nconst SABER_TOKENS = ${JSON.stringify(tokens)};\nconst SABER_VERSION = ${JSON.stringify(version)};\nconst SABER_ROTATION = ${JSON.stringify({ ...rotation, files })};\n${runtime}\n${source}\nreturn { inject: ['theme'], apply };\n  }\n});\n`;
  await mkdir(path.join(root, 'lib'), { recursive: true });
  // Remove obsolete generated chunks without touching unrelated build files.
  for (const file of await readdir(path.join(root, 'lib'))) if (/^client\.wallpaper-\d+\.js$/.test(file) && !files.includes(file)) await rm(path.join(root, 'lib', file), { force: true });
  for (const [i, file] of assets.entries()) {
    const bytes = await readFile(path.join(root, 'theme/assets', file));
    const chunk = `window.__ModuleLoader__.load({id:${JSON.stringify(pkg.name)},chunk:${JSON.stringify(files[i])},factory:()=>({createBlob(){const binary=atob(${JSON.stringify(bytes.toString('base64'))});const bytes=new Uint8Array(binary.length);for(let i=0;i<binary.length;i++)bytes[i]=binary.charCodeAt(i);return new Blob([bytes],{type:'image/webp'});}})});\n`;
    await writeFile(path.join(root, 'lib', files[i]), chunk);
  }
  await writeFile(path.join(root, 'lib/index.js'), await read('src/index.js'));
  // DSH derives the owner revision from client.js; stamp it after all chunks.
  await writeFile(path.join(root, 'lib/client.js'), client);
  return { version, bytes: Buffer.byteLength(client), wallpapers: assets.length };
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { console.log(await build()); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
